/** 버전 → 글 제목 */
export const releaseNoteTitle = (n: ReleaseNote) => `${n.version} · ${n.title}`;

function blocks(n: ReleaseNote): PostBlock[] {
  return [{ p: n.intro }, ...n.sections.flatMap((s): PostBlock[] => [{ h: s.heading }, { ul: s.items }])];
}

/** 글 본문 HTML·요약 글자 */
export const releaseNoteHtml = (n: ReleaseNote) => blocksToHtml(blocks(n));
export const releaseNoteText = (n: ReleaseNote) => blocksToText(blocks(n));
